#!/usr/bin/python3
"""Generate Plasma configuration aliases from the KConfig schema."""
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
entries = ET.parse(root / "package/contents/config/main.xml").getroot().findall(".//{*}entry")
lines = ['// Generated by tools/generate-config.py; edit config/main.xml instead.', 'import QtQuick', '', 'FormKCM {', '    id: configForm']
settings = []
for entry in entries:
    key = entry.attrib['name']
    kind = entry.attrib['type'].lower()
    value = entry.findtext('{*}default') or ''
    if kind == 'bool':
        value = value.lower() == 'true'
    elif kind in ('int', 'uint', 'double'):
        value = float(value) if kind == 'double' else int(value or '0')
    elif kind == 'stringlist':
        value = value.split(',') if value else []
    literal = json.dumps(value, ensure_ascii=False)
    lines += [f'    property alias cfg_{key}: draft.{key}', f'    property var cfg_{key}Default: {literal}']
    settings.append(f'        property var {key}: {literal}')
lines += ['', '    property QtObject settings: QtObject {', '        id: draft'] + settings + ['    }', '}', '']
output = '\n'.join(lines)
target = root / 'package/contents/ui/libconfig/ConfigForm.qml'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != output:
        sys.exit('ConfigForm.qml is stale; run tools/generate-config.py')
else:
    target.write_text(output)
